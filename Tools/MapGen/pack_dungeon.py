"""
Cuts the dungeon props we use out of "16x16 DungeonTileset II" by 0x72 (CC0, https://0x72.itch.io/dungeontileset-ii,
source/0x72_DungeonTilesetII_v1.7.png) and packs them onto a clean 16px grid:

    python Tools/MapGen/pack_dungeon.py

writes Assets/TileSets/TilesetDungeon.png and Assets/TileSets/TilesetDungeon_cells.txt (same format as
pack_desert.py). Unity: Lythrum > Setup > Import Pack Tiles. Map tokens start with `k`.
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "source", "0x72_DungeonTilesetII_v1.7.png")
OUT_PNG = os.path.join(ROOT, "Assets", "TileSets", "TilesetDungeon.png")
OUT_CELLS = os.path.join(ROOT, "Assets", "TileSets", "TilesetDungeon_cells.txt")
COLS, ROWS = 16, 5

# (source x, y, w, h) -> (cell col, cell row, cells wide, cells tall); the sprite is bottom-centred in that block
PIECES = [
    ((288, 432, 16, 16), (0, 0, 1, 1)),   # skull
    ((304, 416, 16, 16), (1, 0, 1, 1)),   # chest (closed)
    ((32, 32, 16, 16), (2, 0, 1, 1)),     # banner blue
    ((16, 32, 16, 16), (3, 0, 1, 1)),     # banner red
    ((16, 48, 16, 16), (4, 0, 1, 1)),     # banner green
    ((32, 48, 16, 16), (5, 0, 1, 1)),     # banner yellow
    ((288, 352, 16, 16), (6, 0, 1, 1)),   # flask red
    ((304, 352, 16, 16), (7, 0, 1, 1)),   # flask blue
    ((320, 352, 16, 16), (8, 0, 1, 1)),   # flask green
    ((336, 352, 16, 16), (9, 0, 1, 1)),   # flask yellow
    ((48, 32, 16, 16), (10, 0, 1, 1)),    # hole in the wall 1
    ((48, 48, 16, 16), (11, 0, 1, 1)),    # hole in the wall 2
    ((48, 96, 16, 16), (12, 0, 1, 1)),    # ladder down
    ((96, 144, 16, 16), (13, 0, 1, 1)),   # hole in the floor
    ((80, 192, 16, 16), (14, 0, 1, 1)),   # stairs
    ((288, 408, 16, 24), (0, 1, 1, 2)),   # crate
    ((80, 80, 16, 48), (1, 1, 1, 3)),     # column
    ((96, 80, 16, 48), (2, 1, 1, 3)),     # column against a wall
    ((64, 0, 16, 16), (3, 1, 1, 1)),      # red fountain: top
    ((64, 16, 16, 16), (3, 2, 1, 1)),     #               middle
    ((64, 32, 16, 16), (3, 3, 1, 1)),     #               basin
    ((80, 0, 16, 16), (8, 1, 1, 1)),      # blue fountain: top
    ((64, 48, 16, 16), (8, 2, 1, 1)),     #                middle
    ((64, 64, 16, 16), (8, 3, 1, 1)),     #                basin
    ((64, 80, 16, 16), (9, 1, 1, 1)),     # goo
    ((64, 96, 16, 16), (9, 2, 1, 1)),     # goo base
    # walls: cap row (top_*) and face row, with the pieces for the two ends of a run
    ((16, 0, 16, 16), (0, 4, 1, 1)),      # wall top left
    ((32, 0, 16, 16), (1, 4, 1, 1)),      # wall top mid
    ((48, 0, 16, 16), (2, 4, 1, 1)),      # wall top right
    ((16, 16, 16, 16), (3, 4, 1, 1)),     # wall left
    ((32, 16, 16, 16), (4, 4, 1, 1)),     # wall mid
    ((48, 16, 16, 16), (5, 4, 1, 1)),     # wall right
    # floors
    ((16, 64, 16, 16), (6, 4, 1, 1)), ((32, 64, 16, 16), (7, 4, 1, 1)), ((48, 64, 16, 16), (8, 4, 1, 1)),
    ((16, 80, 16, 16), (9, 4, 1, 1)), ((32, 80, 16, 16), (10, 4, 1, 1)), ((48, 80, 16, 16), (11, 4, 1, 1)),
    ((16, 96, 16, 16), (12, 4, 1, 1)), ((32, 96, 16, 16), (13, 4, 1, 1)),
    # door: frame + leaf laid out as one 4x3 block at cols 4..7, rows 1..3
    ((32, 224, 32, 16), (5, 1, 2, 1)),    # frame top
    ((16, 240, 16, 32), (4, 2, 1, 2)),    # frame left
    ((32, 240, 32, 32), (5, 2, 2, 2)),    # door leaf (closed)
    ((64, 240, 16, 32), (7, 2, 1, 2)),    # frame right
]


def main():
    src = Image.open(SRC).convert("RGBA")
    out = Image.new("RGBA", (COLS * 16, ROWS * 16), (0, 0, 0, 0))
    for (sx, sy, sw, sh), (cx, cy, cw, ch) in PIECES:
        piece = src.crop((sx, sy, sx + sw, sy + sh))
        x = cx * 16 + (cw * 16 - sw) // 2
        y = cy * 16 + (ch * 16 - sh)
        out.alpha_composite(piece, (x, y))
    out.save(OUT_PNG)

    lines = []
    for r in range(ROWS):
        for c in range(COLS):
            if out.crop((c * 16, r * 16, c * 16 + 16, r * 16 + 16)).getbbox():
                lines.append("%d %d %d" % (c, r, r * COLS + c))
    with open(OUT_CELLS, "w", newline="\n") as f:
        f.write("# col row index - generated by Tools/MapGen/pack_dungeon.py\n" + "\n".join(lines) + "\n")
    print("wrote", OUT_PNG, "with", len(lines), "tiles")


if __name__ == "__main__":
    main()
