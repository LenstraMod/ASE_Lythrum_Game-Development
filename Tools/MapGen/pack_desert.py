"""
Re-packs the free "Desert Ruins 16x16" pack (https://max-m42.itch.io/desert-ruins-16x16-pixel-art-asset,
source/desert_ruins_16x16.png, see source/desert_ruins_LICENSE.txt) onto a clean 16px grid:

    python Tools/MapGen/pack_desert.py

writes Assets/TileSets/TilesetDesert.png and Assets/TileSets/TilesetDesert_cells.txt (one "col row index"
line per non-empty cell; index = row * 16 + col). In Unity, Lythrum > Setup > Import Desert Tiles slices the
PNG and creates the tile assets.

The pack's tiles sit on a 16px grid that starts at (3, 6); its pillar, statue and torches are free-standing
sprites, so they are cut out and re-placed on whole cells (bottom aligned). The brick patch only comes with
its west/north/south edges, so the east-facing variants are mirrored copies.
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "source", "desert_ruins_16x16.png")
OUT_PNG = os.path.join(ROOT, "Assets", "TileSets", "TilesetDesert.png")
OUT_CELLS = os.path.join(ROOT, "Assets", "TileSets", "TilesetDesert_cells.txt")
COLS, ROWS = 16, 10
OX, OY = 3, 6          # where the pack's 16px grid starts


def main():
    src = Image.open(SRC).convert("RGBA")
    out = Image.new("RGBA", (COLS * 16, ROWS * 16), (0, 0, 0, 0))

    # whole sheet shifted onto the grid
    out.alpha_composite(src.crop((OX, OY, OX + COLS * 16, OY + ROWS * 16)))

    # free-standing sprites (absolute pixel boxes in the source)
    pillar = src.crop((119, 10, 139, 47))
    statue = src.crop((151, 6, 171, 37))
    torches = [src.crop(b) for b in ((185, 9, 190, 20), (185, 25, 190, 36), (201, 25, 206, 36))]

    # erase their old (unaligned) pixels
    for box in [(112, 0, 140, 48), (144, 0, 172, 32), (180, 0, 190, 16), (180, 16, 190, 34), (196, 16, 206, 34)]:
        out.paste((0, 0, 0, 0), box)

    def place(img, cell_x, cell_y, cells_w, cells_h):
        """bottom-centre the sprite inside a block of whole cells"""
        x = cell_x * 16 + (cells_w * 16 - img.width) // 2
        y = cell_y * 16 + (cells_h * 16 - img.height)
        out.alpha_composite(img, (x, y))

    place(pillar, 8, 0, 2, 3)      # 2x3 cells
    place(statue, 10, 0, 2, 2)     # 2x2 cells
    for i, t in enumerate(torches):
        place(t, 12 + i, 1, 1, 1)  # row 1, cols 12..14  (three flame colours)

    # mirrored brick-patch pieces (the pack only draws west/north/south edges)
    def cell(c, r):
        return out.crop((c * 16, r * 16, c * 16 + 16, r * 16 + 16))

    def mirror_to(c, r, dst_c, dst_r):
        out.alpha_composite(cell(c, r).transpose(Image.FLIP_LEFT_RIGHT), (dst_c * 16, dst_r * 16))

    mirror_to(2, 0, 0, 6)   # east edge
    mirror_to(3, 0, 1, 6)   # north-east corner
    mirror_to(2, 1, 2, 6)   # south-east corner
    mirror_to(5, 0, 3, 6)   # inner corner, sand at north-east
    mirror_to(4, 1, 4, 6)   # inner corner, sand at south-east

    out.save(OUT_PNG)
    lines = []
    for r in range(ROWS):
        for c in range(COLS):
            if cell(c, r).getbbox():
                lines.append("%d %d %d" % (c, r, r * COLS + c))
    with open(OUT_CELLS, "w", newline="\n") as f:
        f.write("# col row index - generated by Tools/MapGen/pack_desert.py\n" + "\n".join(lines) + "\n")
    print("wrote", OUT_PNG, "with", len(lines), "tiles")


if __name__ == "__main__":
    main()
